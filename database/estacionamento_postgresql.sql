-- Execute dentro de um banco PostgreSQL ja criado.
-- O banco e as credenciais sao fornecidos pelo servico de hospedagem.
CREATE TABLE IF NOT EXISTS veiculo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(100) NOT NULL,
    valor_hora NUMERIC(10,2) NOT NULL,
    horas_estacionado INTEGER NOT NULL DEFAULT 0,
    estacionado BOOLEAN NOT NULL DEFAULT FALSE,
    tipo VARCHAR(20) NOT NULL,
    quantidade_portas INTEGER NULL,
    cilindradas INTEGER NULL
);

